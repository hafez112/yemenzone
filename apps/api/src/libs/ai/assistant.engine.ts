// اقتراحات افتراضية عندما لا يفهم المساعد السؤال
const DEFAULT_CHIPS = ['ما هي يمن زون؟', 'كيف أنشئ متجراً؟', 'كم الأسعار؟', 'طرق الدفع'];

export interface AssistantAnswer {
  reply: string;
  matched: string | null; // معرف القاعدة المطابقة (null = لم يُطابق)
  chips: string[];
}

// الإجابة المحلية: تسجيل نقاط القواعد بالكلمات المطابقة — الأعلى يفوز
export function answerAssistant(message: string, ctx: AssistantContext): AssistantAnswer {
  const norm = normalizeArabic(message || '');
  if (!norm) {
    return { reply: '', matched: null, chips: DEFAULT_CHIPS };
  }

  let best: FaqRule | null = null;
  let bestScore = 0;
  for (const rule of RULES) {
    let s = 0;
    for (const w of rule.keywords) {
      if (norm.includes(normalizeArabic(w))) s++;
    }
    if (s > bestScore) { bestScore = s; best = rule; }
  }

  if (!best) {
    return {
      reply: '',
      matched: null,
      chips: DEFAULT_CHIPS,
    };
  }

  return { reply: best.answer(ctx), matched: best.id, chips: best.chips || DEFAULT_CHIPS };
}

