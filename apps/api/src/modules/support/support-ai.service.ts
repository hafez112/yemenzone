const FALLBACK = 'شكراً لتواصلك مع إدارة يمن زون 🙏\nاستلمنا رسالتك وفريق الدعم سيراجعها ويرد عليك هنا في أقرب وقت خلال ساعات الدوام.\nكلما زوّدتنا بتفاصيل أكثر (أرقام طلبات، أسماء صفحات) كان الرد أسرع وأدق ⚡';

const URGENT_WORDS = ['نصب', 'سرقة', 'سرقه', 'احتيال', 'مستعجل', 'فوري', 'طارئ', 'محامي', 'قضاء', 'فضيحة'];

@Injectable()
export class SupportAiService {
  // تطبيع + مطابقة الكلمات — يعيد أفضل موضوع أو null
  private match(text: string, userType: string): Topic | null {
    const t = normalizeArabic(text || '');
    let best: { topic: Topic; score: number } | null = null;
    for (const topic of TOPICS) {
      if (topic.for !== 'all' && topic.for !== userType) continue;
      const score = topic.keywords.reduce((s, k) => s + (t.includes(normalizeArabic(k)) ? 1 : 0), 0);
      if (score > 0 && (!best || score > best.score)) best = { topic, score };
    }
    return best?.topic || null;
  }

  // رد تلقائي فوري (يُستخدم خارج ساعات الدوام)
  autoReply(text: string, userType: string, userName: string): { reply: string; topic: string } {
    const topic = this.match(text, userType);
    const hello = `أهلاً ${userName || 'بك'} 👋 (رد آلي — فريق الدعم خارج الدوام حالياً)`;
    if (!topic) return { reply: `${hello}\n${FALLBACK}`, topic: 'عام' };
    return { reply: `${hello}\n${topic.reply}\n\nإن لم تحل إجابتك، سيتابع فريق الدعم تذكرتك فور بدء الدوام 🙏`, topic: topic.label };
  }

  // مسودة رد ذكي للإدارة (محلية — تُبنى من آخر رسالة)
  localDraft(text: string, userType: string, userName: string): { draft: string; topic: string } {
    const topic = this.match(text, userType);
    const hello = `أهلاً ${userName || 'بك'} 🌟`;
    if (!topic) {
      return { draft: `${hello}\nشكراً لتواصلك معنا. راجعنا رسالتك وسنوافيك بالتفاصيل الكاملة قريباً.\nهل يمكنك تزويدنا بأي تفاصيل إضافية تساعدنا نخدمك بشكل أدق؟ 🙏`, topic: 'عام' };
    }
    return { draft: `${hello}\n${topic.reply}\n\nنحن في الخدمة لأي استفسار آخر 🌹`, topic: topic.label };
  }

  // أولوية التذكرة من كلمات الاستعجال
  priority(text: string): 'high' | 'normal' {
    const t = normalizeArabic(text || '');
    return URGENT_WORDS.some((k) => t.includes(normalizeArabic(k))) ? 'high' : 'normal';
  }

  // موجه النظام للذكاء الخارجي (عند تفعيله من الإدارة)
  externalSystem(): string {
    return [
      'أنت موظف دعم فني في منصة «يمن زون» — منصة تجارة إلكترونية يمنية (متاجر، بطاقات شحن، توصيل، خدمات مدفوعة).',
      'اكتب رداً عربياً قصيراً (5 أسطر كحد أقصى)، ودوداً ومهنياً، بصيغة المتكلم نيابة عن الإدارة.',
      'قدّم خطوات عملية واضحة، واطلب تفاصيل إضافية إن لزم، ولا تخترع سياسات غير مذكورة.',
      'إن كانت الرسالة اقتراحاً: اشكر صاحبها بحرارة وأخبره أنه سيُدرس من فريق التطوير.',
    ].join('\n');
  }

  // رؤى للإدارة من التذاكر المفتوحة
  insights(tickets: any[]): string[] {
    const tips: string[] = [];
    const open = tickets.filter((t) => t.status === 'open');
    const high = open.filter((t) => t.priority === 'high');
    if (high.length) tips.push(`🔴 ${high.length} تذكرة عالية الأولوية بانتظار الرد — ابدأ بها فوراً`);
    if (open.length) {
      const oldest = open.reduce((a, b) => (new Date(a.createdAt) < new Date(b.createdAt) ? a : b));
      const hrs = Math.floor((Date.now() - new Date(oldest.createdAt).getTime()) / 3_600_000);
      tips.push(`⏳ ${open.length} تذكرة مفتوحة — أقدمها منذ ${hrs} ساعة${hrs > 24 ? ' ⚠️ تجاوزت يوماً!' : ''}`);
    }
    const ideas = tickets.filter((t) => t.category === 'suggestion' && (!t.ideaStatus || t.ideaStatus === 'new'));
    if (ideas.length) tips.push(`💡 ${ideas.length} اقتراح جديد من العملاء والبائعين بانتظار الدراسة — أفكارهم تطوّر المنصة`);
    if (!tips.length) tips.push('✨ لا تذاكر مفتوحة — الدعم تحت السيطرة بالكامل');
    return tips;
  }
}
